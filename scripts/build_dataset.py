def main(out="data"):
    out = pathlib.Path(__file__).resolve().parent.parent / out
    out.mkdir(exist_ok=True)
    w = lambda name, rows: (out / name).write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n", encoding="utf-8")
    corpus, train, test = [], [], []
    for mid, title, director, year, genre, text, tr, te, kw in MOVIES:
        corpus.append(dict(id=mid, title=title, director=director, year=year, genre=genre, text=text))
        train += [dict(query=q, doc_id=mid, level=2) for q in tr]
        test += [dict(query=q, doc_id=mid, level=2) for q in te]
        test += [dict(query=q, doc_id=mid, level=1) for q in kw]
        test.append(dict(query=f"فیلم {title}", doc_id=mid, level=0))
    w("corpus.jsonl", corpus); w("train_queries.jsonl", train); w("test_queries.jsonl", test)
    print(f"corpus={len(corpus)} train={len(train)} test={len(test)}")

if __name__ == "__main__":
    main()
