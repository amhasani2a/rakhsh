"""Creates sample knowledge files in ./samples to try the browser chat."""
import csv, json, pathlib, sqlite3
ROOT = pathlib.Path(__file__).resolve().parent.parent; S = ROOT / "samples"; S.mkdir(exist_ok=True)
movies = [json.loads(l) for l in (ROOT / "data/corpus.jsonl").read_text("utf-8").splitlines()]

# 1) a "book" (plain text with chapters)
book = ["کتاب سینما: سی‌وشش فیلم که باید دید", ""]
for i, m in enumerate(movies, 1):
    book += [f"فصل {i}: {m['title']}", "",
             f"{m['text']}", "",
             f"این فیلم را {m['director']} در سال {m['year']} ساخت و در ژانر {m['genre']} قرار می‌گیرد.", ""]
(S / "cinema_book.txt").write_text("\n".join(book), "utf-8")

# 2) CSV table
with open(S / "movies.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f); w.writerow(["عنوان", "کارگردان", "سال", "ژانر"])
    for m in movies: w.writerow([m["title"], m["director"], m["year"], m["genre"]])

